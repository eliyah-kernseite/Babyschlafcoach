import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { site, offers } from '../src/content.mjs';
import { buildImages } from './images.mjs';

const root = path.resolve(import.meta.dirname, '..');
// Photo versions first: the page templates measure them as soon as they are loaded.
const made = await buildImages();
if (made.length) console.log(`Bildversionen erstellt: ${made.join(', ')}`);
const { pages } = await import('../src/pages.mjs');
const { legalPages } = await import('../src/legal.mjs');
const { layout, updated, cleanPath } = await import('../src/layout.mjs');

// Browser configuration for the booking form, generated from content/einstellungen.yml.
await writeFile(path.join(root, 'assets/config.js'), `// Generated by scripts/build.mjs from content/einstellungen.yml. Edit the content file, not this one.
// Public configuration only. Never put credentials or private calendar data here.
export const site = Object.freeze(${JSON.stringify(site)});

// These are request lengths, not an assertion of live calendar availability.
export const offers = Object.freeze([
${offers.map(o => `  ${JSON.stringify(o)},`).join('\n')}
]);
`);
const allPages = { ...pages, ...legalPages };
for (const [file, page] of Object.entries(allPages)) {
  if (!/^[a-z0-9-]+\.html$/.test(file)) throw new Error(`Invalid page path: ${file}`);
  await writeFile(path.join(root, file), layout(file, page));
}
const urls = Object.entries(allPages).filter(([, p]) => !p.noindex).map(([file]) => new URL(cleanPath(file), site.url).href);
await writeFile(path.join(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(url => `  <url><loc>${url}</loc><lastmod>${updated}</lastmod></url>`).join('\n')}\n</urlset>\n`);
await writeFile(path.join(root, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site.url}sitemap.xml\n`);
console.log(`Built ${Object.keys(allPages).length} static pages, sitemap.xml and robots.txt.`);
